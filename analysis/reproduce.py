# -*- coding: utf-8 -*-
"""Recompute every threshold, mean, SD and figure of the seven PDF figure sets from the public CSVs.

    python analysis/reproduce.py            # all seven tests
    python analysis/reproduce.py smrt gdt   # selected tests

All values are computed from data/trials/*.csv and data/runs/*.csv only; analysis/pdf_values/<test>.csv (the
numbers printed in the PDFs) is read only for the comparison. For each test it writes to analysis/output/<test>/:
  numbers.csv          every value it computed (full precision)
  pdf_comparison.csv   each value printed in the PDF next to the recomputed value, formatted the same way
  figures/             the figures again (multi-page PDF + one PNG per page)
A run of all seven tests also writes analysis/output/VERIFICATION.md and verification_summary.csv; a run of
selected tests leaves those two files as they are and only prints its summary.
"""
import csv
import importlib
import io
import os
import sys
import time

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

TESTS = ['tmtf', 'smrt', 'stripes', 'stm', 'srd', 'gdt', 'smd']
PDF = {'tmtf': 'TMTF_English.pdf / TMTF_Korean.pdf', 'smrt': 'Figure1_SMRT_detailed_EN.pdf / _KO.pdf',
       'stripes': 'STRIPES_scientific_figures_EN.pdf / _KO.pdf', 'stm': 'STM_Scientific_EN.pdf / _KO.pdf',
       'srd': 'SRD_scientific_EN.pdf / _KO.pdf', 'gdt': 'GDT_scientific_EN.pdf / _KO.pdf', 'smd': 'SMD_scientific_EN.pdf / _KO.pdf'}


def main(tests):
    import common
    out_root = os.path.join(HERE, 'output')
    os.makedirs(out_root, exist_ok=True)
    summary, all_mismatch = [], []
    for t in tests:
        t0 = time.time()
        od = os.path.join(out_root, t)
        os.makedirs(od, exist_ok=True)
        mod = importlib.import_module(t)
        values, checks = mod.run(od)
        common.write_numbers({**values, **{f'check.{k}': v for k, v in checks.items()}}, od)
        res = common.compare(t, values, od, getattr(mod, 'ROUNDING', 'float'))
        n_ok = sum(r['match'] for r in res)
        mism = [r for r in res if not r['match']]
        all_mismatch += mism
        summary.append(dict(test=t.upper(), pdf=PDF[t], pdf_values=len(res), identical=n_ok, different=len(mism),
                            figure_pages=checks.get('figure_pages', ''),
                            internal_checks='; '.join(f'{k}={v}' for k, v in checks.items() if k != 'figure_pages'),
                            seconds=round(time.time() - t0, 1)))
        print(f'{t.upper():8s} PDF values {len(res):4d}  identical {n_ok:4d}  different {len(mism):3d}  '
              f'figure pages {checks.get("figure_pages", "")}  ({time.time() - t0:.1f} s)')
        for r in mism[:15]:
            print(f'    {r["key"]}: PDF {r["pdf"]!r}  recomputed {r["computed"]!r}')
    print(f'TOTAL identical {sum(s["identical"] for s in summary)} / {sum(s["pdf_values"] for s in summary)}')
    if sorted(tests) != sorted(TESTS):
        print('(selected tests only: VERIFICATION.md and verification_summary.csv were not rewritten)')
        return 0 if not all_mismatch else 1
    with open(os.path.join(out_root, 'verification_summary.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(summary[0].keys()), lineterminator='\n')
        w.writeheader()
        w.writerows(summary)
    with open(os.path.join(out_root, 'VERIFICATION.md'), 'w', encoding='utf-8') as f:
        f.write('# Recomputed values vs. the PDF figure sets\n\n')
        f.write('Generated by `python analysis/reproduce.py`. Every value is computed from `data/trials/*.csv` and '
                '`data/runs/*.csv` only; `analysis/pdf_values/<test>.csv` holds the numbers printed in the PDFs (with page and '
                'panel) and is read only for this comparison. The PDFs themselves are not part of this package. '
                'A value counts as identical when the recomputed number, formatted with the same number of decimals '
                'as printed in the PDF, is the same text.\n\n')
        f.write('| test | PDF | values checked | identical | different | figure pages | internal checks |\n|---|---|---:|---:|---:|---:|---|\n')
        for s in summary:
            f.write(f"| {s['test']} | {s['pdf']} | {s['pdf_values']} | {s['identical']} | {s['different']} | {s['figure_pages']} | "
                    f"{s['internal_checks']} |\n")
        tot = sum(s['pdf_values'] for s in summary)
        ok = sum(s['identical'] for s in summary)
        f.write(f'\n**Total: {ok} of {tot} PDF values identical.**\n')
        f.write('\nNotes\n\n'
                '- TMTF: the PDF was made from the records up to 2026-11-03 (142 runs); the eight 2026-11-04 runs are left out '
                '(`PDF_LAST_DATE` in tmtf.py). Run thresholds are rounded to 0.01 dB as the app stores them before averaging.\n'
                '- SMRT: run thresholds are rounded to 0.0001 RPO as the app stores them; the PDF SDs were computed from those values.\n'
                '- SRD: reversal densities are summed in integer milli-RPO as in the app (0.96025 -> 0.9603).\n'
                '- SMD: the PDF rounds exact halves up (21.325 -> 21.33), so this comparison rounds half up; the default '
                'binary formatting would print 21.32.\n'
                '- English and Korean PDFs carry the same numbers; values were taken from the English text layer.\n'
                '- Not compared (not computed from data): design constants in the methods text, literature reference lines, '
                'the GDT sample-quantisation example, and the PDFs\' own source hashes.\n')
        if all_mismatch:
            f.write('\n## Values that differ\n\n| test | key | PDF | recomputed | where |\n|---|---|---|---|---|\n')
            for r in all_mismatch:
                f.write(f"| {r['test']} | {r['key']} | {r['pdf']} | {r['computed']} | {r['where']} |\n")
    return 0 if not all_mismatch else 1


if __name__ == '__main__':
    sel = [a.lower() for a in sys.argv[1:]] or TESTS
    sys.exit(main(sel))
